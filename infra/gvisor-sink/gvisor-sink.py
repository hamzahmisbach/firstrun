#!/usr/bin/env python3
"""Receive gVisor runtime-monitoring trace points over the remote-sink protocol and append
them as JSON lines, one file per container (docs/ARCHITECTURE.md 7.1-7.2).

Protocol (pkg/sentry/seccheck/sinks/remote): runsc connects to a SOCK_SEQPACKET Unix socket,
sends a bare Handshake proto, expects ours back, then sends packets of
<header_size u16><message_type u16><dropped_count u32><protobuf payload> (little-endian).
"""

import argparse
import json
import os
import re
import socket
import struct
import sys
import threading
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "pb"))  # generated by scripts/build-sink-protos.sh

from google.protobuf.json_format import MessageToDict  # noqa: E402
from google.protobuf.message import DecodeError  # noqa: E402
from pkg.sentry.seccheck.points import common_pb2, container_pb2, sentry_pb2, syscall_pb2  # noqa: E402

PROTOCOL_VERSION = 1
HEADER = struct.Struct("<HHI")
MAX_PACKET = 1 << 20  # gVisor's reference server reads with the same buffer size
MAX_DECODED_PER_CONN = 50_000  # beyond this a flooding sandbox is only counted, not decoded
MAX_CLONES_PER_CONN = 20_000  # forks only link the process tree, so they cannot use up the budget above
HEARTBEAT_SECONDS = 10
CONTAINER_ID = re.compile(r"^[0-9a-f]{64}$")

DECODERS = {
    common_pb2.MESSAGE_CONTAINER_START: container_pb2.Start,
    common_pb2.MESSAGE_SENTRY_CLONE: sentry_pb2.CloneInfo,
    common_pb2.MESSAGE_SENTRY_EXEC: sentry_pb2.ExecveInfo,
    common_pb2.MESSAGE_SYSCALL_OPEN: syscall_pb2.Open,
    common_pb2.MESSAGE_SYSCALL_CONNECT: syscall_pb2.Connect,
}

log_lock = threading.Lock()


def now_ms():
    return int(time.time() * 1000)


def log(record):
    with log_lock:
        print(json.dumps(record, separators=(",", ":")), flush=True)


class Connection:
    """State for one sandbox connection: per-container output files and counters."""

    def __init__(self, conn_id, out_dir, echo):
        self.conn_id = conn_id
        self.out_dir = out_dir
        self.echo = echo
        self.files = {}
        self.received = 0
        self.dropped = 0
        self.decode_errors = 0
        self.ignored = 0
        self.capped = 0
        self.clones = 0

    def file_for(self, container_id):
        name = container_id if CONTAINER_ID.match(container_id) else f"unknown-{self.conn_id}"
        handle = self.files.get(name)
        if handle is None:
            handle = open(os.path.join(self.out_dir, f"{name}.jsonl"), "a", encoding="utf-8", buffering=1)
            self.files[name] = handle
        return handle

    def write(self, container_id, record):
        line = json.dumps(record, separators=(",", ":"))
        self.file_for(container_id).write(line + "\n")
        if self.echo:
            log(record)

    def packet(self, data):
        self.received += 1
        if len(data) < HEADER.size:
            self.decode_errors += 1
            return
        header_size, message_type, dropped = HEADER.unpack_from(data)
        if header_size < HEADER.size or header_size > len(data):
            self.decode_errors += 1
            return
        self.dropped = dropped
        if message_type == common_pb2.MESSAGE_SENTRY_CLONE:
            self.clones += 1
            if self.clones > MAX_CLONES_PER_CONN:
                return
        elif self.received - self.clones > MAX_DECODED_PER_CONN:
            self.capped += 1
            return
        message_class = DECODERS.get(message_type)
        if message_class is None:
            self.ignored += 1
            return
        message = message_class()
        try:
            message.ParseFromString(data[header_size:])
        except DecodeError:
            self.decode_errors += 1
            return
        body = MessageToDict(message, preserving_proto_field_name=True)
        container_id = body.get("context_data", {}).get("container_id") or body.get("id") or ""
        self.write(container_id, {
            "src": "gvisor",
            "conn": self.conn_id,
            "recv_ms": now_ms(),
            "type": message_type,
            "dropped": dropped,
            "container_id": container_id,
            "msg": body,
        })

    def close(self):
        summary = {
            "src": "gvisor",
            "kind": "sink.closed",
            "conn": self.conn_id,
            "recv_ms": now_ms(),
            "received": self.received,
            "dropped": self.dropped,
            "decode_errors": self.decode_errors,
            "ignored": self.ignored,
            "capped": self.capped,
        }
        for name, handle in self.files.items():
            handle.write(json.dumps(dict(summary, container_id=name), separators=(",", ":")) + "\n")
            handle.close()
        log(summary)


def handshake(conn, conn_id):
    hello = common_pb2.Handshake()
    hello.ParseFromString(conn.recv(10240))
    if hello.version < PROTOCOL_VERSION:
        log({"kind": "sink.handshake_rejected", "conn": conn_id, "version": hello.version})
        return False
    conn.send(common_pb2.Handshake(version=PROTOCOL_VERSION).SerializeToString())
    return True


def handle(conn, conn_id, args):
    state = Connection(conn_id, args.out_dir, args.stdout)
    try:
        if not handshake(conn, conn_id):
            return
        while True:
            data = conn.recv(MAX_PACKET)
            if not data:
                break
            state.packet(data)
    except (OSError, DecodeError) as err:
        log({"kind": "sink.conn_error", "conn": conn_id, "error": str(err)})
    finally:
        state.close()
        conn.close()


def heartbeat(path):
    while True:
        try:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(str(now_ms()))
        except OSError as err:
            log({"kind": "sink.heartbeat_error", "error": str(err)})
        time.sleep(HEARTBEAT_SECONDS)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--socket", required=True, help="Unix socket path runsc connects to")
    parser.add_argument("--out-dir", required=True, help="directory for <container_id>.jsonl files")
    parser.add_argument("--stdout", action="store_true", help="also print every record (debugging)")
    args = parser.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    if os.path.exists(args.socket):
        os.unlink(args.socket)
    server = socket.socket(socket.AF_UNIX, socket.SOCK_SEQPACKET)
    server.bind(args.socket)
    os.chmod(args.socket, 0o660)
    server.listen(16)
    threading.Thread(target=heartbeat, args=(args.socket + ".heartbeat",), daemon=True).start()
    log({"kind": "sink.listening", "socket": args.socket, "out_dir": args.out_dir})

    conn_id = 0
    while True:
        conn, _ = server.accept()
        conn_id += 1
        threading.Thread(target=handle, args=(conn, conn_id, args), daemon=True).start()


if __name__ == "__main__":
    main()
